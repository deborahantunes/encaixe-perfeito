// Bundles the game's judging rules (src/game/challenges.ts + data + rules) into server/shared/challenges.mjs,
// so the room server scores exactly like the game. Run after changing stages or rules: pnpm build:shared
import { build } from 'esbuild'

export async function buildShared(outfile = 'server/shared/challenges.mjs', write = true) {
  const r = await build({
    entryPoints: ['src/game/challenges.ts'], bundle: true, format: 'esm', platform: 'node', target: 'node20',
    outfile, write, legalComments: 'none',
    // The server never shows text: replace the translation tables with a Portuguese-only t().
    plugins: [{
      name: 'no-i18n',
      setup(b) {
        b.onResolve({ filter: /\/i18n$/ }, () => ({ path: 'i18n', namespace: 'stub' }))
        b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
          contents: 'export const t = (s, p) => { if (p) for (const [k, v] of Object.entries(p)) s = s.split(`{${k}}`).join(String(v)); return s }',
          loader: 'js',
        }))
      },
    }],
    banner: { js: '// Generated by scripts/build-shared.mjs from src/game/challenges.ts — do not edit.' },
  })
  return write ? null : r.outputFiles[0].text
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildShared()
  console.log('server/shared/challenges.mjs atualizado')
}
