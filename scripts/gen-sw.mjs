// Writes dist/sw.js: a service worker that precaches every shipped file so the game runs offline
// (e.g. on a Meta Quest without internet after one online visit).
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const dist = 'dist'
const files = []
const walk = dir => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p)
    else files.push(relative(dist, p).split('\\').join('/'))
  }
}
walk(dist)
const assets = files.filter(f => f !== 'sw.js' && !f.endsWith('.txt') && !f.endsWith('.map')).sort()
const hash = createHash('sha256')
for (const f of assets) hash.update(f).update(readFileSync(join(dist, f)))
const version = hash.digest('hex').slice(0, 12)
const list = JSON.stringify(['./', ...assets.filter(f => f !== 'index.html')].map(f => (f === './' ? f : `./${f}`)))

writeFileSync(join(dist, 'sw.js'), `// Generated by scripts/gen-sw.mjs — do not edit.
const CACHE = 'encaixe-${version}'
const ASSETS = ${list}

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('encaixe-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()))
})

self.addEventListener('message', event => {
  if (event.data === 'status') {
    caches.open(CACHE).then(c => c.keys()).then(keys => event.source.postMessage({ type: 'offline-status', ready: keys.length >= ASSETS.length, version: CACHE }))
  }
})

self.addEventListener('fetch', event => {
  const req = event.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return
  if (req.mode === 'navigate') {
    // Fresh page when online, cached game when offline.
    event.respondWith(fetch(req).catch(() => caches.match('./', { cacheName: CACHE, ignoreVary: true, ignoreSearch: true })))
    return
  }
  event.respondWith(caches.match(req, { cacheName: CACHE, ignoreSearch: true, ignoreVary: true }).then(hit => hit || fetch(req)))
})
`)
console.log(`sw.js: ${assets.length} arquivos guardados para offline (versão ${version})`)
